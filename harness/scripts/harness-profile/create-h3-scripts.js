var fs = require("fs");
var h = "C:/Codex_App_Factory/harness";

// ===== compile-profile-domain-pack.ps1 =====
var compiler = [
'# compile-profile-domain-pack.ps1 — Phase 6C-H3',
'# Reads a profile, domain skill pack, and domain verifier pack,',
'# then emits a compiled run package with a generated run contract.',
'param(',
'    [Parameter(Mandatory=$true)][string]$ProfilePath,',
'    [Parameter(Mandatory=$true)][string]$DomainSkillPath,',
'    [Parameter(Mandatory=$true)][string]$DomainVerifierPath,',
'    [Parameter(Mandatory=$true)][string]$OutputDir',
')',
'',
'$ErrorActionPreference = "Continue"',
'$errors = [System.Collections.ArrayList]::new()',
'$passes = [System.Collections.ArrayList]::new()',
'$exitCode = 0',
'',
'# Load inputs',
'if (-not (Test-Path $ProfilePath)) { [void]$errors.Add("PROFILE_NOT_FOUND"); exit 1 }',
'if (-not (Test-Path $DomainSkillPath)) { [void]$errors.Add("DOMAIN_SKILL_NOT_FOUND"); exit 1 }',
'if (-not (Test-Path $DomainVerifierPath)) { [void]$errors.Add("VERIFIER_PACK_NOT_FOUND"); exit 1 }',
'',
'try { $profile = Get-Content $ProfilePath -Raw -Encoding UTF8 | ConvertFrom-Json } catch { [void]$errors.Add("PROFILE_INVALID_JSON"); exit 1 }',
'try { $domain = Get-Content $DomainSkillPath -Raw -Encoding UTF8 | ConvertFrom-Json } catch { [void]$errors.Add("DOMAIN_SKILL_INVALID_JSON"); exit 1 }',
'try { $verifier = Get-Content $DomainVerifierPath -Raw -Encoding UTF8 | ConvertFrom-Json } catch { [void]$errors.Add("VERIFIER_PACK_INVALID_JSON"); exit 1 }',
'',
'[void]$passes.Add("All inputs loaded")',
'',
'# Validate profile-domain match',
'if ($profile.profileId -and $domain.domainId) {',
'    [void]$passes.Add("Profile $($profile.profileId) + Domain $($domain.domainId)")',
'} else {',
'    [void]$errors.Add("PROFILE_DOMAIN_MISMATCH: missing IDs"); $exitCode = 1',
'}',
'',
'# Validate worker responsibilities cover domain entities',
'$domainEntities = $domain.domainEntities | ForEach-Object { $_.entityId }',
'$assignedEntities = @()',
'if ($domain.requiredWorkerResponsibilities) {',
'    $domain.requiredWorkerResponsibilities | ForEach-Object {',
'        if ($_.assignedEntities) { $script:assignedEntities += $_.assignedEntities }',
'    }',
'}',
'$unassignedEntities = $domainEntities | Where-Object { $_ -notin $assignedEntities }',
'if ($unassignedEntities.Count -gt 0) {',
'    [void]$errors.Add("UNASSIGNED_ENTITIES: $($unassignedEntities -join ', ')")',
'    $exitCode = 1',
'} else {',
'    [void]$passes.Add("All $($domainEntities.Count) entities assigned to workers")',
'}',
'',
'# Validate profile complexity is not lowered by domain',
'$profMinWorkers = $profile.defaultComplexityBudget.minimumWorkers',
'$domainWorkers = ($domain.requiredWorkerResponsibilities | Measure-Object).Count',
'if ($domainWorkers -lt $profMinWorkers) {',
'    [void]$errors.Add("PROFILE_COMPLEXITY_LOWERED: domain workers=$domainWorkers < profile minimum=$profMinWorkers")',
'    $exitCode = 1',
'} else {',
'    [void]$passes.Add("Complexity: domain workers $domainWorkers >= profile $profMinWorkers")',
'}',
'',
'# Generate run contract',
'$runContract = [ordered]@{',
'    runId = "h3-compiled-$($profile.profileId)-$($domain.domainId)"',
'    phase = "Phase 6C-H3"',
'    projectProfile = $profile.profileId',
'    domainId = $domain.domainId',
'    requiredWorkers = $domainWorkers',
'    requiredTasks = $domain.requiredDomainScenarios.Count',
'    minimumJsFiles = $profile.defaultComplexityBudget.minimumJsFiles',
'    minimumNamedExports = $profile.defaultComplexityBudget.minimumNamedExports',
'    minimumCrossWorkerDeps = $profile.defaultComplexityBudget.minimumCrossWorkerDeps',
'    requiredScenarioCount = $verifier.acceptanceScenarios.Count,',
'    requiredAcceptanceLayers = $profile.defaultAcceptanceLayers,',
'    requiredArtifacts = $profile.recommendedArtifacts,',
'    requiredNegativeControls = $verifier.negativeControls.Count,',
'    noExternalPackages = $true,',
'    nodeBuiltinsOnly = $true,',
'    requireRunState = $true,',
'    requireWorkerFreeze = $true,',
'    requireIntegrationLedger = $true,',
'    requireVerifierHashLock = $true,',
'    forbiddenSimplifications = $profile.forbiddenSimplifications,',
'    domainInvariants = $domain.invariants,',
'    domainBusinessRuleCount = $domain.businessRules.Count,',
'    sourceProfile = $ProfilePath,',
'    sourceDomainSkill = $DomainSkillPath,',
'    sourceVerifierPack = $DomainVerifierPath',
'}',
'',
'# Write output',
'New-Item -ItemType Directory -Force -Path $OutputDir | Out-Null',
'$runContract | ConvertTo-Json -Depth 5 | Set-Content (Join-Path $OutputDir "run-contract.json") -Encoding UTF8',
'$profile | ConvertTo-Json -Depth 5 | Set-Content (Join-Path $OutputDir "profile.json") -Encoding UTF8',
'$domain | ConvertTo-Json -Depth 5 | Set-Content (Join-Path $OutputDir "domain-skill-pack.json") -Encoding UTF8',
'$verifier | ConvertTo-Json -Depth 5 | Set-Content (Join-Path $OutputDir "domain-verifier-pack.json") -Encoding UTF8',
'',
'[void]$passes.Add("Compiled to $OutputDir")',
'',
'$verdict = if ($exitCode -eq 0) { "PASS" } else { "FAIL" }',
'$result = @{',
'    verdict = $verdict',
'    profileId = $profile.profileId',
'    domainId = $domain.domainId',
'    workerCount = $domainWorkers',
'    scenarioCount = $verifier.acceptanceScenarios.Count',
'    negativeCount = $verifier.negativeControls.Count',
'    entityCount = $domainEntities.Count',
'    unassignedEntities = $unassignedEntities',
'    outputDir = $OutputDir',
'    passCount = $passes.Count',
'    failCount = $errors.Count',
'    passes = $passes',
'    errors = $errors',
'    timestamp = (Get-Date).ToString("o")',
'}',
'Write-Output ($result | ConvertTo-Json -Depth 3)',
'exit $exitCode'
].join("\n");
fs.writeFileSync(h + "/scripts/harness-profile/compile-profile-domain-pack.ps1", compiler, "utf8");

// ===== validate-profile-boundary.ps1 =====
var profGuard = [
'# validate-profile-boundary.ps1 — Phase 6C-H3',
'# Profiling guard. Fails if profile attempts to hardcode domain knowledge.',
'param(',
'    [Parameter(Mandatory=$true)][string]$ProfilePath',
')',
'',
'$ErrorActionPreference = "Continue"',
'$errors = [System.Collections.ArrayList]::new()',
'$passes = [System.Collections.ArrayList]::new()',
'$exitCode = 0',
'',
'if (-not (Test-Path $ProfilePath)) {',
'    Write-Output (@{ verdict="FAIL"; reason="PROFILE_NOT_FOUND" } | ConvertTo-Json)',
'    exit 1',
'}',
'',
'try { $profile = Get-Content $ProfilePath -Raw -Encoding UTF8 | ConvertFrom-Json }',
'catch { Write-Output (@{ verdict="FAIL"; reason="PROFILE_INVALID_JSON" } | ConvertTo-Json); exit 1 }',
'',
'# Domain-specific terms that should NOT appear in profiles',
'$domainTerms = @("SKU","stock","inventory","ticket","agent","workload","invoice","payment","shipment","customer","order","booking","schedule","notification")',
'',
'$profileText = Get-Content $ProfilePath -Raw -Encoding UTF8',
'$foundTerms = @()',
'foreach ($term in $domainTerms) {',
'    if ($profileText -match "\\b$term\\b") { $foundTerms += $term }',
'}',
'',
'if ($foundTerms.Count -gt 0) {',
'    [void]$errors.Add("PROFILE_BOUNDARY_VIOLATION: domain terms in profile: $($foundTerms -join ', ')")',
'    $exitCode = 1',
'} else {',
'    [void]$passes.Add("Profile boundary clean: no domain terms in profile")',
'}',
'',
'# Check profile does not define domain entities or business rules',
'if ($profile.domainEntities -or $profile.businessRules -or $profile.invariants) {',
'    [void]$errors.Add("PROFILE_CONTAINS_DOMAIN_STRUCTURES: domain entities/rules/invariants must be in domain pack, not profile")',
'    $exitCode = 1',
'} else {',
'    [void]$passes.Add("Profile has no domain structures (correct)")',
'}',
'',
'# Check complexity budget has not been zeroed',
'$budget = $profile.defaultComplexityBudget',
'if ($budget.minimumWorkers -le 0) { [void]$errors.Add("COMPLEXITY_ZEROED: minimumWorkers <= 0"); $exitCode = 1 }',
'if ($budget.minimumJsFiles -le 0) { [void]$errors.Add("COMPLEXITY_ZEROED: minimumJsFiles <= 0"); $exitCode = 1 }',
'if ($budget.minimumScenarios -le 0) { [void]$errors.Add("COMPLEXITY_ZEROED: minimumScenarios <= 0"); $exitCode = 1 }',
'',
'$verdict = if ($exitCode -eq 0) { "PASS" } else { "FAIL" }',
'$result = @{',
'    verdict = $verdict',
'    profileId = $profile.profileId',
'    domainTermsFound = $foundTerms',
'    passCount = $passes.Count',
'    failCount = $errors.Count',
'    passes = $passes',
'    errors = $errors',
'    timestamp = (Get-Date).ToString("o")',
'}',
'Write-Output ($result | ConvertTo-Json -Depth 3)',
'exit $exitCode'
].join("\n");
fs.writeFileSync(h + "/scripts/harness-profile/validate-profile-boundary.ps1", profGuard, "utf8");

// ===== detect-domain-knowledge-gaps.ps1 =====
var gapDetector = [
'# detect-domain-knowledge-gaps.ps1 — Phase 6C-H3',
'# Checks a compiled run package for domain knowledge coverage gaps.',
'param(',
'    [Parameter(Mandatory=$true)][string]$CompiledDir',
')',
'',
'$ErrorActionPreference = "Continue"',
'$gaps = [System.Collections.ArrayList]::new()',
'$passes = [System.Collections.ArrayList]::new()',
'$exitCode = 0',
'$severityCounts = @{ critical=0; high=0; medium=0; low=0 }',
'',
'$domainPath = Join-Path $CompiledDir "domain-skill-pack.json"',
'$verifierPath = Join-Path $CompiledDir "domain-verifier-pack.json"',
'$contractPath = Join-Path $CompiledDir "run-contract.json"',
'',
'if (-not (Test-Path $domainPath)) { [void]$gaps.Add(@{type="MISSING_DOMAIN";severity="critical";detail="domain-skill-pack.json not found"}); $severityCounts.critical++; $exitCode=1 }',
'if (-not (Test-Path $verifierPath)) { [void]$gaps.Add(@{type="MISSING_VERIFIER";severity="critical";detail="domain-verifier-pack.json not found"}); $severityCounts.critical++; $exitCode=1 }',
'',
'if ((Test-Path $domainPath) -and (Test-Path $verifierPath)) {',
'    try { $domain = Get-Content $domainPath -Raw -Encoding UTF8 | ConvertFrom-Json } catch { [void]$gaps.Add(@{type="DOMAIN_JSON_INVALID";severity="critical";detail="Cannot parse domain-skill-pack.json"}); $severityCounts.critical++; $exitCode=1 }',
'    try { $verifier = Get-Content $verifierPath -Raw -Encoding UTF8 | ConvertFrom-Json } catch { [void]$gaps.Add(@{type="VERIFIER_JSON_INVALID";severity="critical";detail="Cannot parse domain-verifier-pack.json"}); $severityCounts.critical++; $exitCode=1 }',
'',
'    if ($domain -and $verifier) {',
'        # Gap 1: Business rule without acceptance scenario',
'        $scenarioNames = $verifier.acceptanceScenarios | ForEach-Object { $_.scenarioId }',
'        if ($domain.businessRules) {',
'            foreach ($rule in $domain.businessRules) {',
'                # Check if any scenario covers this rule (via acceptanceImplication keyword match)',
'                $covered = $false',
'                foreach ($sc in $verifier.acceptanceScenarios) {',
'                    if ($sc.description -match $rule.ruleId -or $sc.description -match $rule.description.Substring(0,[Math]::Min(20,$rule.description.Length))) { $covered = $true; break }',
'                }',
'                if (-not $covered) {',
'                    [void]$gaps.Add(@{type="RULE_WITHOUT_SCENARIO";severity=$rule.severity;detail="Rule $($rule.ruleId): $($rule.description)";ruleId=$rule.ruleId})',
'                    $severityCounts[$rule.severity]++',
'                    $exitCode = 1',
'                }',
'            }',
'            if ($gaps.Count -eq 0) { [void]$passes.Add("All business rules have acceptance scenarios") }',
'        }',
'',
'        # Gap 2: Business rule without negative control',
'        if ($verifier.negativeControls) {',
'            $negTargets = $verifier.negativeControls | ForEach-Object { $_.targetsScenario }',
'            foreach ($sc in $verifier.acceptanceScenarios) {',
'                if ($sc.scenarioId -notin $negTargets) {',
'                    [void]$gaps.Add(@{type="SCENARIO_WITHOUT_NEGATIVE";severity="medium";detail="Scenario $($sc.scenarioId): $($sc.description) has no negative control";scenarioId=$sc.scenarioId})',
'                    $severityCounts.medium++',
'                    $exitCode = 1',
'                }',
'            }',
'            if (($verifier.acceptanceScenarios | Where-Object { $_.scenarioId -notin $negTargets }).Count -eq 0) {',
'                [void]$passes.Add("All scenarios have negative controls")',
'            }',
'        }',
'',
'        # Gap 3: Invariant not covered by scenario',
'        if ($domain.invariants -and $verifier.invariantChecks) {',
'            $coveredInvariants = $verifier.invariantChecks | ForEach-Object { $_.invariant }',
'            foreach ($inv in $domain.invariants) {',
'                $found = $coveredInvariants | Where-Object { $inv -match $_ -or $_ -match $inv }',
'                if (-not $found) {',
'                    [void]$gaps.Add(@{type="INVARIANT_WITHOUT_SCENARIO";severity="high";detail="Invariant not covered: $inv";invariant=$inv})',
'                    $severityCounts.high++',
'                    $exitCode = 1',
'                }',
'            }',
'            if (($domain.invariants | Where-Object { $inv = $_; -not ($coveredInvariants | Where-Object { $inv -match $_ -or $_ -match $inv }) }).Count -eq 0) {',
'                [void]$passes.Add("All invariants covered by scenarios")',
'            }',
'        }',
'',
'        # Gap 4: Domain entity not assigned to any worker',
'        if ($domain.domainEntities -and $domain.requiredWorkerResponsibilities) {',
'            $domainEntityIds = $domain.domainEntities | ForEach-Object { $_.entityId }',
'            $assigned = @()',
'            $domain.requiredWorkerResponsibilities | ForEach-Object {',
'                if ($_.assignedEntities) { $script:assigned += $_.assignedEntities }',
'            }',
'            foreach ($eid in $domainEntityIds) {',
'                if ($eid -notin $assigned) {',
'                    [void]$gaps.Add(@{type="ENTITY_NOT_ASSIGNED";severity="high";detail="Entity $eid not assigned to any worker";entityId=$eid})',
'                    $severityCounts.high++',
'                    $exitCode = 1',
'                }',
'            }',
'            if (($domainEntityIds | Where-Object { $_ -notin $assigned }).Count -eq 0) {',
'                [void]$passes.Add("All entities assigned to workers")',
'            }',
'        }',
'',
'        # Gap 5: Forbidden assumption without verifier coverage',
'        if ($domain.forbiddenAssumptions) {',
'            foreach ($fa in $domain.forbiddenAssumptions) {',
'                $covered = $false',
'                foreach ($sc in $verifier.acceptanceScenarios) {',
'                    $keywords = $fa -split "\\s+"',
'                    if ($keywords | Where-Object { $sc.description -match $_ }) { $covered = $true; break }',
'                }',
'                if (-not $covered) {',
'                    [void]$gaps.Add(@{type="ASSUMPTION_NOT_COVERED";severity="medium";detail="Forbidden assumption not covered: $fa";assumption=$fa})',
'                    $severityCounts.medium++',
'                    $exitCode = 1',
'                }',
'            }',
'        }',
'',
'        # Gap 6: No example data for required workflow',
'        if ($domain.workflows -and $domain.exampleData) {',
'            $wfNames = $domain.workflows | ForEach-Object { $_.name }',
'            $exNames = $domain.exampleData | ForEach-Object { $_.scenario }',
'            foreach ($wf in $wfNames) {',
'                if ($wf -notin $exNames) {',
'                    [void]$gaps.Add(@{type="WORKFLOW_WITHOUT_EXAMPLE";severity="low";detail="Workflow without example data: $wf";workflow=$wf})',
'                    $severityCounts.low++',
'                }',
'            }',
'        }',
'    }',
'}',
'',
'$verdict = if ($exitCode -eq 0) { "PASS" } else { "FAIL_GAPS_DETECTED" }',
'$result = @{',
'    verdict = $verdict',
'    gapCount = $gaps.Count',
'    gaps = $gaps',
'    severityCounts = $severityCounts',
'    passCount = $passes.Count',
'    passDetails = $passes',
'    checkedAt = (Get-Date).ToString("o")',
'}',
'Write-Output ($result | ConvertTo-Json -Depth 4)',
'exit $exitCode'
].join("\n");
fs.writeFileSync(h + "/scripts/harness-profile/detect-domain-knowledge-gaps.ps1", gapDetector, "utf8");

console.log("3 H3 scripts created: compiler, profile guard, gap detector");
